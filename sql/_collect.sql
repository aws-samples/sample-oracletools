-- oracletools - shared SQL*Plus driver.
-- Do not call directly: use collect_awr.sql (default), collect_noawr.sql or collect_statspack.sql.
-- Expects: collection_mode (AWR|NOAWR|STATSPACK) and collection_dir (awr|noawr|statspack) defined.
-- Must be started from the sql/ directory; CSV files are written to ./output.
-- =============================================================================
SET ECHO OFF
SET TERMOUT ON
SET VERIFY OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 32767
SET TRIMSPOOL ON
SET TRIMOUT ON
SET TAB OFF
SET WRAP OFF
SET DEFINE ON
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WRAPPED
WHENEVER SQLERROR CONTINUE
WHENEVER OSERROR CONTINUE

DEFINE tool_version = 1.1.0

-- Force '.' as decimal separator so the CSV files are locale independent
ALTER SESSION SET NLS_NUMERIC_CHARACTERS = '.,';

-- File name prefix: <server>_<db name>
SET TERMOUT OFF
COLUMN host_prefix NEW_VALUE host_prefix NOPRINT
SELECT LOWER(SYS_CONTEXT('USERENV', 'SERVER_HOST')) || '_' || LOWER(NAME) AS host_prefix FROM V$DATABASE;
SET TERMOUT ON

PROMPT ============================================================
PROMPT  oracletools &tool_version - collection mode: &collection_mode
PROMPT  Output directory: ./output
PROMPT ============================================================

PROMPT [1/3] Collection metadata  -> output/&host_prefix._collection_info.csv
SPOOL output/&host_prefix._collection_info.csv
@common/collection_info.sql
SPOOL OFF

PROMPT [2/3] Instance level data  -> output/&host_prefix._oracle_instance_level_data.csv
SPOOL output/&host_prefix._oracle_instance_level_data.csv
@&collection_dir/instance_level.sql
SPOOL OFF

PROMPT [3/3] Database level data and features (current container, then every open PDB)
@_container.sql

-- Build a script that switches into every open PDB (only when connected to CDB$ROOT, 12c+)
SET TERMOUT OFF
SPOOL output/&host_prefix._pdb_loop.sql
DECLARE
    v_version_num NUMBER;
    v_is_cdb VARCHAR2(3) := 'NO';
    v_con_id NUMBER := 0;
    TYPE t_names IS TABLE OF VARCHAR2(128);
    v_pdbs t_names := t_names();
BEGIN
    DBMS_OUTPUT.PUT_LINE('-- Generated by oracletools: one entry per open PDB');
    SELECT TO_NUMBER(REGEXP_SUBSTR(VERSION, '[0-9]+')) INTO v_version_num FROM V$INSTANCE;
    IF v_version_num >= 12 THEN
        EXECUTE IMMEDIATE 'SELECT CDB FROM V$DATABASE' INTO v_is_cdb;
        v_con_id := TO_NUMBER(SYS_CONTEXT('USERENV', 'CON_ID'));
        IF v_is_cdb = 'YES' AND v_con_id = 1 THEN
            EXECUTE IMMEDIATE
                'SELECT NAME FROM V$PDBS WHERE NAME <> ''PDB$SEED'' AND OPEN_MODE LIKE ''READ%'' ORDER BY CON_ID'
                BULK COLLECT INTO v_pdbs;
            FOR i IN 1 .. v_pdbs.COUNT LOOP
                DBMS_OUTPUT.PUT_LINE('PROMPT ---- PDB ' || v_pdbs(i));
                DBMS_OUTPUT.PUT_LINE('ALTER SESSION SET CONTAINER = "' || v_pdbs(i) || '";');
                DBMS_OUTPUT.PUT_LINE('@_container.sql');
            END LOOP;
            IF v_pdbs.COUNT > 0 THEN
                DBMS_OUTPUT.PUT_LINE('ALTER SESSION SET CONTAINER = CDB$ROOT;');
            END IF;
        END IF;
    END IF;
END;
/
SPOOL OFF
SET TERMOUT ON
@output/&host_prefix._pdb_loop.sql

PROMPT
PROMPT Collection complete. Copy all CSV files from ./output and process them with:
PROMPT   python3 oracle_collector.py process --input <folder with the CSV files>
PROMPT
EXIT
